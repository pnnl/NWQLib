REAL_REASON = "QFD has no structural real proof for its time-evolved basis states"


def _generator_statement(target, generator):
    """Return the Plan assumption that names the fermionic generator B of V and its distance from the target A.

    ``target`` holds A's ``(label, coefficient)`` rows and ``generator`` B's
    exact coefficients (``construction.fermionic_step``). The two distances
    are the outward-rounded upper bounds of ``generator_difference``.
    """
    nonidentity, full = generator_difference(target, generator)
    shift = float(generator["I" * len(next(iter(generator)))])
    relation = ("B equals A, so delta_gen_0 = delta_gen_full = 0." if full == 0 else
                "B differs from A, so it is an approximate evolution generator. Upper bounds from exact rational "
                f"sums rounded up once: delta_gen_0 = sum_{{P != I}} |a_P - b_P| = {nonidentity!r} >= ||A0 - B0|| and "
                f"delta_gen_full = |c_I - c_B| + delta_gen_0 = {full!r} >= ||A - B||.")
    return (f"V is generated by the complete number-conserving fermionic blocks of evolution_terms, B = c_B I + B0 "
            f"with c_B = {shift!r}, which enters neither V nor an energy. {relation} These do not bound the distance "
            "of V from exp(-i tau A0) and are not energy error bars.")


def _sector_statement(reference):
    """Return the Plan assumption on the particle-number sector of a fermionic-block basis.

    Every supported block is complete and number conserving, so the basis
    lies in the sector of the reference when the reference is a particle
    number eigenstate. That is established without forming the state only
    for an occupation, or for a product whose every qubit factor has one
    exact zero amplitude, a computational basis state up to phase. Mode j
    is qubit j with ``|1>`` occupied, so N counts the occupied qubits.
    """
    physical, implementation = reference._physical, reference.preparation.implementation
    number = None
    if physical is not None and implementation == "qiskit.occupation":
        number = int(physical.sum())
    elif physical is not None and implementation == "qiskit.product" and all(
            np.count_nonzero(factor) == 1 for factor in physical):
        number = int(np.count_nonzero(physical[:, 1]))
    if number is None:
        return (f"no particle-number sector is stated for the basis, because a {reference.reference.representation} "
                "reference has an established particle number only as an occupation or a product of computational "
                "basis states")
    return (f"the basis lies in the particle-number sector N = {number} of the reference, because every evolution "
            "block is a complete number-conserving fermionic block. With exact H and S, the Ritz value is a "
            "Rayleigh-quotient value of A on a state of that sector, and so an upper bound on the smallest eigenvalue "
            "of A and, when A also conserves the particle number, which is not checked, on the smallest eigenvalue of "
            "A in that sector. Spin projection and total spin are not qualified, since evolution_terms has no spin "
            "labels.")


class QFD(Method):
    """Quantum filter diagonalization: the lowest Ritz energy of A in the basis of integer powers of one fixed product-formula step V.

    Build it with keyword arguments and pass it as `method=`, for example
    `solve(Eigenproblem(A=H), method=QFD(initial_state=psi, time_step=0.5,
    powers=(0, 1, 2)), shots=1000)`. `initial_state`, `time_step` and
    `powers` are required. Write `A = c_I I + A0`. The basis state of power
    p is `phi_p = V**p |psi>` for one fixed step V, which applies
    `steps_per_time_step = r` substeps of a product formula for
    `time_step/r`, of `A0` by default or of the fermionic blocks of `B0`
    with `evolution="fermionic_blocks"`, with order 2 (the default) or
    order 1. A negative power applies the exact adjoint of V, its rotations
    in reverse order with negated angles. The result is a
    [`QFDResult`][nwqlib.algorithms.qfd.records.QFDResult] whose
    `eigenvalue` is the lowest kept Ritz value of `H f = E S f`, with
    `H_jk = <phi_j|A|phi_k>` and `S_jk = <phi_j|phi_k>` measured for the
    original A, and whose `reference_energy` is `<psi|A|psi>`. This is the
    Hamiltonian pencil of Parrish and McMahon, arXiv:1909.08925v1,
    Sec. II.C, Eqs. (5)-(8), with the states of one fixed step in place of
    exact time evolution. The step, its order and r define the trial
    space, so changing them changes the basis, and none of them is an
    accuracy setting. A projected Ritz value does not certify the
    full-space ground energy.

    V is built once, and its emitted angles are saved with the Plan. With
    the default `evolution="pauli_terms"` its factors are the nonidentity
    Pauli terms of `A0` in the Plan's label order. Each factor is the
    rotation `exp(-i theta P/2)`: order 1 applies every term for the
    substep `dt = time_step/r`, with `theta = 2 c dt` for the coefficient
    c, and order 2 applies every term for `dt/2` and then every term again
    in reverse order, with `theta = c dt`. The identity term contributes
    only a global phase and is left out of V, and the solve adds `c_I`
    back to the Ritz values.

    With `evolution="fermionic_blocks"` V comes instead from an explicit
    fermionic generator `B = c_B I + B0` in `evolution_terms`, while H, S
    and the energies remain those of A. B is split into complete Hermitian
    blocks, one for the real and one for the imaginary part of each pair of
    adjoint ladder terms, or one for a self-adjoint term. The blocks are
    number, hopping, density, hopping times a spectator number, and
    double-excitation terms. A block maps under Jordan-Wigner to commuting
    Pauli words, so the rotations of its words give its exponential
    exactly. Order 1 applies every block once, and order 2 applies every
    block for half the substep and then every block again in reverse
    order. Each block conserves the particle number, and V applies the
    exponential of every block whole, never split or interleaved with
    another, so V conserves it as well. A product formula of the Pauli
    terms of A in their label order need not conserve it even when A does.
    The constant `c_B` is left out of V and never enters an energy, so a B
    without nonidentity terms gives V = I and a basis of copies of psi. The
    Plan's `assumptions` state the upper bounds
    `delta_gen_0 = sum_{P != I} |a_P - b_P|` on `||A0 - B0||` and
    `delta_gen_full = |c_I - c_B| + delta_gen_0` on `||A - B||`, which do
    not bound the distance of V from `exp(-i tau A0)`, and they state
    whether the basis lies in the particle-number sector of the reference.
    That needs an occupation reference or a product of computational basis
    states. With exact H and S, the Ritz value is then a Rayleigh-quotient
    value of A on a state of that sector, and so an upper bound on the
    smallest eigenvalue of A and, when A itself conserves the particle
    number, which QFD does not check, on the smallest eigenvalue of A in
    that sector. Spin projection and total spin are not qualified, since
    `evolution_terms` has no spin labels.

    Quantum execution only. A pair `i < j` prepares the joint state
    `(|0>|phi_i> + |1>|phi_j>)/sqrt(2)` of one ancilla and the system. With
    the default `pair_preparation="prefix"` of `acquisition`, the end of
    smaller absolute power b (the smaller index on a tie) runs the
    reference and `V**b` once without control, and the remaining power
    difference is controlled on the ancilla, so only the difference costs
    controlled steps. With `"controlled"` both complete preparations are
    controlled. With `shots=None` (exact readout) every pair is reduced to
    `H0_ij` and `S_ij` from its simulated state. With `shots=n` each pair
    and each of the G qubit-wise commuting groups of terms is one setting,
    off-diagonal pairs in both the X and Y ancilla bases, so a basis of M
    powers has `M**2 G` settings and `n M**2 G` shots. The quadratures are
    always complex, even for a real A, because the time-evolved states are
    complex in general. With `sampling=PencilSampling(...)` in place of
    `shots=`, the same settings are measured in a uniform pilot stage and
    again in a main stage whose shots per setting the pilot pencil decides,
    and only the main-stage measurements form H, S and the reference
    energy. A setting stops the run when its circuit fails
    `max_native_two_qubit_depth`, with the earlier settings' counts kept.
    `overlap_cutoff` can be changed after the run with
    `result.analyze(overlap_cutoff=...)`, which reuses the same matrix
    elements.

    Attributes:
        initial_state: Required. The reference state psi, in a form that
            `StateData` accepts, prepared with its phase once per circuit,
            except an off-diagonal pair under `pair_preparation="controlled"`,
            which prepares it under control on both ancilla branches.
            An occupation or product state keeps planning compact on many
            qubits.
        time_step: Required, finite and positive. The time step tau of V in
            inverse units of the Hamiltonian's energy (with hbar = 1), for
            example 1/Hartree for a Hamiltonian in Hartree.
        powers: Required. Distinct integers including 0, the powers of V
            in basis order. Their order is the order of the rows and columns
            of H and S, and 0 need not come first.
        steps_per_time_step: Default `1`. The number r of product-formula
            substeps of V, fixed for every power.
        formula_order: Default `2`. Product-formula order of each substep,
            1 or 2.
        evolution: Default `"pauli_terms"`, the product formula of the Pauli
            terms of A above. `"fermionic_blocks"` builds V from the complete
            fermionic blocks of `evolution_terms`.
        evolution_terms: Default None. Required with
            `evolution="fermionic_blocks"` and None otherwise: the generator
            B as a fermionic `OperatorInput` from
            [`ingest_fermion`][nwqlib.operators._fermion.ingest_fermion] or
            [`chemistry_evolution_terms`][nwqlib.algorithms.qfd.chemistry.chemistry_evolution_terms].
            Its coefficients are read in the energy unit of A. Mode j acts
            on qubit j of A, with `|1>` occupied, so B has as many modes as
            A has qubits. Each row is a scalar, `a_p^dagger a_q` or
            `a_p^dagger a_q^dagger a_r a_s`, written with its creations left
            of its annihilations, and B must be exactly Hermitian: after
            normal ordering the coefficients of each term and of its adjoint
            are exact complex conjugates, and that of a self-adjoint term is
            real. Planning refuses other operators. Its content hash is part
            of the Method's.
        evolution_diagnostics: Default None. The
            [`QFDEvolutionDiagnostics`][nwqlib.algorithms.qfd.records.QFDEvolutionDiagnostics]
            that `chemistry_evolution_terms` returned with `evolution_terms`,
            saved with the Method. It requires `evolution="fermionic_blocks"`,
            and its `evolution_input` must equal the content hash of
            `evolution_terms`. A generator from another source needs none.
        overlap_cutoff: Default `1e-12`, positive. Overlap eigenvectors with
            eigenvalues above it are kept for the solve.
        max_basis_size: Default `64`. Largest accepted number of powers.
        max_experiments: Default `100_000`. Largest number of settings:
            exact pair reductions, or sampled group settings.
        max_bytes: Default 10 GB (decimal, `10_000_000_000` bytes). Limit on
            the known bytes of conversion, the pair table, the grouped count
            analysis and the projected solve, and on each exact pair
            reduction's workspace.
        max_analysis_work: Default `1_000_000_000`. Limit on the work of the
            projected solve, of the comparisons that form qubit-wise
            commuting groups and of each pass of the grouped count analysis,
            checked at planning for one measurement per setting and again
            before the stored counts are decoded.
        max_classical_products: Default `100_000_000`. Limit on the summed
            classical work of the exact pair reductions.
        input_conversion: Default `"auto"`, which keeps Pauli input as it
            is and converts an explicit dense matrix of dimension at most 16
            to Pauli form. `"dense_pauli"` also permits the conversion of
            sparse matrices and of larger dense matrices, within
            `max_conversion_work` and `max_bytes`.
        max_conversion_work: Default `100_000_000`. Limit on the counted work
            of operator-to-Pauli conversion.
        max_admission_steps: Default `10_000_000`. Limit on the planning work
            of checking each `Program` that the method builds
            ([planning work limit](../../development/program_checks.md#planning-work-limit)),
            on the number of uses of V in all its circuits, checked before
            the circuits are described, and on the circuit instructions of
            the distinct evolution blocks that the Plan uses (V, its adjoint
            and their controlled forms), each r times the instructions of
            one substep, checked at planning before any block is built. Each
            of the three counts is compared with the limit separately.
        acquisition: Default `PencilAcquisition()`. QFD measures grouped
            joint states, so `matrix_measurement` must be `"grouped"`, and
            `pair_preparation` is `"prefix"` or `"controlled"`. ADAPT's
            `"vacuum_reference"` and `"vacuum_restore"` need a known vacuum
            phase, and QFD records and computes none for V, so planning
            raises `ApplicabilityError` for either value whenever the Plan
            measures anything, that is, for every A that is not a multiple of the
            identity, `powers=(0,)` included, with exact readout and with
            shots alike. For a multiple of the identity the request is kept
            unused, with resolved `pair_preparation` None, and no circuit
            runs. A Plan with
            shots measures complex quadratures and rejects
            `quadratures="real"` at planning. With exact readout, which
            measures no quadratures, the requested value has no effect and
            is recorded as None. The Plan records the resolved choices, with
            the construction of every pair, in
            `plan.reconstruction.pencil.acquisition`.
        max_native_two_qubit_depth: Default `None`, which requests no depth
            limit. A nonnegative integer D requires each submitted circuit,
            every grouped count setting and every exact pair reduction, to
            have a native two-qubit depth of at most D, with D itself
            allowed. The depth is that of the circuit the backend prepared
            for execution, with the reference preparation, the uncontrolled
            and controlled powers of V, the measurement basis changes and
            the backend's qubit routing. Each circuit is checked just before
            its submission, and one whose depth exceeds D or is unavailable
            is not submitted: the run raises
            `nwqlib.backends.inspection.NativeDepthCapRefusal`. Settings
            submitted earlier keep their counts and shots in the Run. The
            limit changes no circuit, power or term. Only IBM Runtime
            computes this depth, under the conditions that
            [`FixedGCIM`][nwqlib.algorithms.gcim.fixed_basis.FixedGCIM]
            describes for the same field. Under `sampling` it applies to
            every pilot and main circuit.
        sampling: Default `None`, which measures every setting with the
            `shots=` of the call. A
            [`PencilSampling`][nwqlib.algorithms.gcim.fixed_basis.PencilSampling]
            replaces `shots=` with a pilot stage and a main stage whose
            shots per setting the pilot decides, as for `FixedGCIM`. The
            Result's `shot_allocation` records that decision.
            `nwqlib.estimate(plan)` then reports the totals of the whole
            Plan, such as its settings and shots, as unavailable, because
            each setting is measured in a pilot stage and again in a main
            stage whose shots the pilot decides. One prepared setting, whose
            stage and shots are fixed, is estimated normally from its
            preparation record. The shot budget of a Run is
            `PencilSampling.total_shots`.

    Raises:
        ValueError: If `acquisition` requests termwise measurement, if
            `evolution_terms` is missing with `"fermionic_blocks"`, set with
            `"pauli_terms"` or not fermionic, or if `evolution_diagnostics`
            does not belong to `evolution_terms` on that route.

    Examples:
        For `A = -Z` on one qubit, `psi = (|0> + |1>)/sqrt(2)`, a time step
        of 0.5 and the powers 0 and 1, the two basis states span the qubit,
        so on Aer with exact readout the lowest Ritz value is the ground
        energy -1 up to rounding, which lies 1 below the reference energy
        0:

        >>> from nwqlib import Eigenproblem, solve
        >>> from nwqlib.algorithms import QFD
        >>> from nwqlib.operators import ingest_pauli
        >>> from nwqlib.problems import ingest_product
        >>> A = ingest_pauli((("Z", -1.0),), num_qubits=1)
        >>> psi = ingest_product([[2**-0.5, 2**-0.5]])
        >>> result = solve(Eigenproblem(A=A), method=QFD(initial_state=psi, time_step=0.5, powers=(0, 1)),
        ...                seed=7)
        >>> print(round(result.eigenvalue, 10), round(result.lowering, 10))
        -1.0 1.0

        With the fermionic generator `B = 5 + n_0`, where
        `n_0 = a_0^dagger a_0 = (I - Z)/2`, V rotates the same psi about Z,
        and the two basis states again span the qubit. H and S belong to
        `A = 3 I + X`, so the lowest Ritz value is its ground energy 2 and
        the reference energy is `<psi|A|psi> = 4`. The constant 5 of B
        enters neither V nor an energy:

        >>> from nwqlib.operators import ingest_fermion
        >>> A = ingest_pauli((("I", 3.0), ("X", 1.0)), num_qubits=1)
        >>> B = ingest_fermion([(5.0, []), (1.0, [(0, 1), (0, 0)])], num_modes=1)
        >>> method = QFD(initial_state=psi, time_step=2.5, powers=(0, 1), evolution="fermionic_blocks",
        ...              evolution_terms=B)
        >>> result = solve(Eigenproblem(A=A), method=method, seed=7)
        >>> print(round(result.eigenvalue, 10), round(result.reference_energy, 10))
        2.0 4.0
    """

    schema_version: Literal[1] = 1
    initial_state: StateData
    time_step: Annotated[Real, Field(gt=0)]
    powers: Annotated[tuple[StrictInt, ...], Field(min_length=1)]
    steps_per_time_step: PositiveInt = 1
    formula_order: Literal[1, 2] = 2
    evolution: Literal["pauli_terms", "fermionic_blocks"] = "pauli_terms"
    evolution_terms: OperatorData | None = None
    evolution_diagnostics: QFDEvolutionDiagnostics | None = None
    overlap_cutoff: Annotated[Real, Field(gt=0)] = 1e-12
    # The limits share FixedGCIM's untuned workload ceilings on derived
    # counts, checked before expansion (docs/ENGINEERING_CONSTANTS.md).
    max_basis_size: PositiveInt = 64
    max_experiments: PositiveInt = 100_000
    max_bytes: PositiveInt = DEFAULT_MAX_BYTES
    max_analysis_work: PositiveInt = 1_000_000_000
    max_classical_products: PositiveInt = 100_000_000
    input_conversion: Literal["auto", "dense_pauli"] = "auto"
    max_conversion_work: PositiveInt = DEFAULT_CONVERSION_WORK
    max_admission_steps: PositiveInt = 10_000_000
    acquisition: PencilAcquisition = PencilAcquisition()
    max_native_two_qubit_depth: Count | None = None
    sampling: PencilSampling | None = None
    result_type: ClassVar[type] = QFDResult

    descriptor: ClassVar[AlgorithmDescriptor] = DESCRIPTOR

    @model_validator(mode="after")
    def _grouped_only(self):
        """QFD has only the grouped joint-state construction."""
        if self.acquisition.matrix_measurement != "grouped":
            raise ValueError("QFD measures grouped joint states; matrix_measurement='termwise' is "
                             "ADAPT's comparison construction")
        return self

    @model_validator(mode="after")
    def _generator(self):
        """A fermionic generator comes exactly with the fermionic route, and its diagnostics name that generator."""
        terms = self.evolution_terms
        if (self.evolution == "fermionic_blocks") != (terms is not None):
            raise ValueError("QFD evolution_terms is required exactly with evolution='fermionic_blocks'")
        if terms is not None and terms.reference.representation != "fermion":
            raise ValueError("QFD evolution_terms must be a fermionic OperatorInput, for example from ingest_fermion, "
                             f"not a {terms.reference.representation} operator")
        diagnostics = self.evolution_diagnostics
        if diagnostics is not None and (terms is None or diagnostics.evolution_input != terms.reference.identity):
            raise ValueError("QFD evolution_diagnostics belong to the evolution_terms whose content hash is "
                             f"{diagnostics.evolution_input}, not to this Method's generator")
        return self

    def plan(self, problem, *, output, execution, shots, rng):
        """Fix V, the basis powers and the pair constructions, and choose the measurement of H and S."""
        if execution != "quantum":
            raise ApplicabilityError("QFD prepares its time-evolved basis on a quantum register; "
                                     "use execution='quantum'")
        if self.sampling is not None:
            if shots is not None:
                raise ValueError("QFD.sampling sets the shots of every setting and stage; omit shots=")
            # Plan.shots marks a counts Plan at the two-shot stage minimum.
            # The stages bind each setting's actual shots (gcim.pencil_workflow).
            shots = 2
        if problem.subspace is not None:
            raise ApplicabilityError("QFD generates its own basis and does not accept a requested subspace")
        if problem.sector is not None:
            raise ApplicabilityError(
                "QFD does not establish a symmetry of A, so it accepts no requested Problem sector. With "
                "evolution='fermionic_blocks' the Plan's assumptions state whether the basis lies in the particle-number "
                "sector of the reference.")
        powers, b = self.powers, len(self.powers)
        if len(set(powers)) != b:
            raise ValueError(f"QFD powers {powers} repeat a power, which prepares the same state twice")
        if 0 not in powers:
            raise ValueError(f"QFD powers {powers} must include 0, the reference state")
        if b > self.max_basis_size:
            raise ValueError(f"QFD has {b} powers, more than QFD.max_basis_size={self.max_basis_size}, "
                             "before pair expansion")
        d = problem.dimension
        if d & (d - 1):
            raise ApplicabilityError(f"QFD evolves the qubit register of A, whose dimension {d} is not a power of two")
        operator = eigen_operator(problem, output, max_bytes=self.max_bytes, input_conversion=self.input_conversion,
                                  max_conversion_work=self.max_conversion_work)
        reference = eigen_state(self.initial_state, problem, max_bytes=self.max_bytes)
        q = operator.basis.dimension.bit_length() - 1
        from nwqlib.algorithms.gcim.adapt_inputs import _packed_to_pauli_arrays, pauli_array_conversion_requirements

        table = operator.pauli_terms()
        _check_bytes(pauli_array_conversion_requirements(len(table), q)[1] + 64 * len(table), self.max_bytes,
                     "QFD Pauli term table")
        input_terms = _packed_to_pauli_arrays(table.x, table.z, table.coefficients.real, q)
        nonidentity = len(input_terms.coefficients.array) - int((~input_terms.labels.array.any(axis=1)).any())
        rule = self.acquisition.pair_preparation
        positions = {sign: 1 + index for index, sign in enumerate(
            sign for sign in (1, -1) if any(sign * p > 0 for p in powers))}
        pairs, uses = macro_uses(powers, rule) if nonidentity else ((), {})
        acquisition = resolve_acquisition(
            self.acquisition, execution=execution, shots=shots, acquires=bool(nonidentity),
            real_reason=lambda: REAL_REASON, scope=f"recorded Hamiltonian Pauli terms and all {b} QFD basis states",
            pairs=pairs)
        quadratures = acquisition.quadratures or "complex"
        groups, e = _pencil_admission(self, q, b, input_terms, nonidentity, shots, quadratures, label="QFD",
                                      sampling=self.sampling)
        pencil_record = FixedGCIMReconstruction(terms=input_terms, basis_size=b, num_qubits=q, groups=groups,
                                                acquisition=acquisition)
        substep = self.time_step / self.steps_per_time_step
        if self.evolution == "pauli_terms":
            rows = pencil_record.nonidentity_terms
            step_rows, step_angles = (step_factors(rows, substep, self.formula_order) if rows
                                      else (np.zeros(0, np.int64), np.zeros(0, np.float64)))
            if not np.isfinite(step_angles).all():
                raise ValueError("QFD time step and coefficients give a nonfinite rotation angle")
            evolution = step_blocks = generator = None
            source = operator
        else:
            fermions = self.evolution_terms.fermion_terms()
            if fermions.num_modes != q:
                raise ValueError(f"QFD evolution_terms has {fermions.num_modes} modes and A has {q} qubits; mode j "
                                 "acts on qubit j, so the two must agree")
            # A string of k ladder operators and its adjoint map to at most
            # 2**k Pauli words each, so this bounds the rows of B's table and
            # the factors of one block sweep before any word is formed.
            lengths = np.diff(fermions.offsets).tolist()
            bound = 1 + 2 * sum(1 << length for length in lengths)
            _check_bytes(pauli_array_conversion_requirements(bound, q)[1] + 64 * bound, self.max_bytes,
                         "QFD evolution_terms table")
            shift, blocks = fermionic_blocks(self.evolution_terms, max_bytes=self.max_bytes)
            evolution, step_rows, step_angles, starts, generator = fermionic_step(
                shift, blocks, substep, self.formula_order, q)
            step_blocks, source = FrozenArray(starts), self.evolution_terms
        reconstruction = QFDReconstruction(
            pencil=pencil_record, substep=substep, step_rows=FrozenArray(step_rows),
            step_angles=FrozenArray(step_angles), reference_index=powers.index(0), evolution=evolution,
            step_blocks=step_blocks)
        if generator is not None:
            rows = reconstruction.evolution_rows
        blocks, definitions, experiments, staged = [], [], [], {}
        registers, classical = (), ()
        if e:
            # Each pair circuit calls V or its adjoint as often as
            # macro_uses counts, each call a Program step, and its recipe
            # holds one position per call, so the uses are checked before
            # the pair recipes and circuits are built. A sampled pair has
            # one circuit per group and quadrature, two quadratures off the
            # diagonal.
            calls = sum(count * ((1 if i == j else 2) * len(groups) if shots else 1)
                        for (i, j), count in uses.items())
            if calls > self.max_admission_steps:
                raise ValueError(f"QFD circuits call V or its adjoint {calls} times in all, exceeding "
                                 f"max_admission_steps={self.max_admission_steps}. Reduce the powers or the basis size.")
            recipes = power_pair_recipes(powers, rule, positions)
            prepared = [select_preparation("reference", reference)]
            controlled = {}
            for sign, position in positions.items():
                kind = "forward" if sign > 0 else "adjoint"
                prepared.append(evolution_block(kind, rows, step_rows, step_angles, self.steps_per_time_step,
                                                source, q))
                controlled[position] = evolution_block("controlled_" + kind, rows, step_rows, step_angles,
                                                       self.steps_per_time_step, source, q)
            metadata = MetadataRef(format=METHOD, data=reference.reference)
            if shots:
                settings = tuple(sampled_settings(pencil_pairs(b), len(groups), quadratures))
                blocks, definitions, experiments, staged = _sampled_construction(
                    prepared, recipes, q, metadata, groups, shots, settings, controlled, sampling=self.sampling)
                classical = (
                    ClassicalValue(name="phase", dtype="bits", width=1),
                    ClassicalValue(name="system_bits", dtype="bits", width=q),
                )
            else:
                blocks, definitions, experiments = _exact_pair_construction(
                    prepared, recipes, b, operator, q, metadata, controlled)
            # Building a distinct evolution block that the experiments use
            # appends r times the instructions of one substep, so the sum over
            # these blocks is checked here, before any block circuit is built.
            # It is a separate count from the uses of V and the Program steps.
            work = sum({block.record.content_id: block.record.construction_work for block in blocks
                        if block.record.implementation == EVOLUTION}.values())
            if work > self.max_admission_steps:
                raise ValueError(
                    f"The QFD evolution blocks of {self.steps_per_time_step} substeps each take {work} circuit "
                    f"instructions in all, exceeding QFD.max_admission_steps={self.max_admission_steps}. Raise "
                    "max_admission_steps to build this V. Fewer steps_per_time_step define a different V.")
            registers = (
                Register(name="ancilla", width=1, role="clean_ancilla"),
                Register(name="system", width=q),
            )
        definitions.append(Definition(id="root", node=Sequence(children=tuple(exp.batch for exp in experiments))))
        program = admitted_program(
            "QFD.max_admission_steps",
            self.max_admission_steps,
            root="root",
            definitions=tuple(definitions),
            registers=registers,
            classical=classical,
            signatures=tuple(block.record.signature for block in blocks),
            **staged,
        )
        construction = SelectedConstruction(program=program, selections=tuple(block.record for block in blocks))
        from types import SimpleNamespace
        from nwqlib.algorithms._eigen_support import eigen_error_model

        components = SimpleNamespace(output=output, problem=problem, construction=construction)
        generator_statements = () if generator is None else (
            _generator_statement(input_terms.rows(), generator), _sector_statement(reference))
        plan = Plan(
            problem=problem,
            method=self,
            output=output,
            execution=execution,
            shots=shots,
            randomness=rng.snapshot(),
            construction=construction,
            experiments=tuple(experiments),
            reconstruction=reconstruction,
            assumptions=(
                "basis states are integer powers of one fixed realized V applied to the reference",
                *generator_statements,
                "H_identity=c*S uses the same overlap observations",
                "projected estimate does not establish smallest full-space eigenvalue",
            ),
            error_model=eigen_error_model(components, METHOD),
        )
        if e and not shots:
            # The summed registered work of the pair reductions is recorded
            # once in the Plan's cache and admitted at preparation.
            _pair_work_total(plan)
            return plan._bind(blocks=blocks, operator=operator, reference=reference,
                              pair_table=_pair_table(operator))
        return plan._bind(blocks=blocks, operator=operator, reference=reference)

