    def analyze(self, plan, data, *, settings):
        """Reconstruct the obtained pencil of the fixed-V basis, solve it and report the reference energy.

        Under PencilSampling the grouped pass reads the main-stage chunks
        only, and the Result carries the frozen ``ShotAllocation`` of the
        saved iteration state (``gcim.pencil_workflow.frozen_allocation``),
        so neither the pilot solve nor the allocation is repeated.
        """
        cutoff = settings.get("overlap_cutoff", self.overlap_cutoff)
        if not isinstance(cutoff, (int, float)) or not 0 < cutoff < float("inf"):
            raise ValueError("overlap_cutoff must be finite and positive")
        rec = plan.reconstruction.pencil
        fields = dict(estimates=(), pairs=(), group_moments=(), sampled_pair_variances=())
        if self.sampling is not None:
            from nwqlib.algorithms.gcim.pencil_workflow import frozen_allocation, stage_chunks

            fields["shot_allocation"] = frozen_allocation(plan, data)
        if not rec.nonidentity_coefficients:
            # A multiple of the identity has no acquisition, so its value is
            # the identity coefficient and no H or S is formed.
            tuple(matched_chunks(plan, data))
            shift = rec.identity_shift
            missing, ids, pencil = (), (), None
            eigenvalue, reference, lowering = shift, shift, 0.0
        else:
            if plan.shots is None:
                fields["pairs"], missing, ids, pencil = exact_pair_pencil(self, plan, data, rec, cutoff, label="QFD")
            else:
                chunks = tuple(chunk for chunk, _ in matched_chunks(plan, data))
                if self.sampling is not None:
                    chunks = stage_chunks(chunks, 1)
                moments = read_groups(
                    chunks, rec.settings(),
                    members=[group.indices for group in rec.groups], rows=rec.nonidentity_terms,
                    num_qubits=rec.num_qubits, basis_size=rec.basis_size, max_bytes=self.max_bytes,
                    max_analysis_work=self.max_analysis_work, label="QFD")
                estimates, missing, pairs, variances = pooled_statistics(rec.settings(), moments, rec.identity_shift)
                pencil = None
                if not missing:
                    h, s = assemble_pair_pencil(rec.basis_size, pairs)
                    pencil = solve_pencil(h, s, cutoff=cutoff, sampled=True, enclosure=processed_pauli_enclosure(rec),
                                          identity_shift=rec.identity_shift)
                ids = tuple(row.contribution_id for row in moments)
                fields.update(estimates=estimates, group_moments=moments, sampled_pair_variances=variances)
            eigenvalue = pencil.eigenvalues[0] if pencil is not None and pencil.eigenvalues else None
            i0 = plan.reconstruction.reference_index
            reference = None if pencil is None else pencil.hamiltonian[i0][i0].real
            lowering = None if eigenvalue is None else reference - eigenvalue
        return QFDResult(
            plan_id=plan.content_id,
            construction_id=plan.construction.content_id,
            observation_id=data.observations.content_id,
            contribution_ids=ids,
            eigenvalue=eigenvalue,
            reference_energy=reference,
            lowering=lowering,
            missing=missing,
            pencil=pencil,
            analysis_cutoff=cutoff,
            origin=capture_analysis_origin(analyzer=METHOD, method_id=self.content_id,
                                           dependencies=("numpy", "scipy")),
            facts=exact_readout_sampling(plan, data.observations, random_draws=False),
            **fields,
        )._attach(plan, data)

