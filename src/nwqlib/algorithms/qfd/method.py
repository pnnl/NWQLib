"""Quantum filter diagonalization (QFD) in a fixed product-formula basis.

The basis states are integer powers ``V**p`` of one fixed product-formula
step V of the centered Hamiltonian ``A0 = A - c_I I``, or of the complete
fermionic blocks of an explicit centered generator ``B0 = B - c_B I``,
applied to one reference. The projected matrices ``H = Phi^dagger A Phi`` and
``S = Phi^dagger Phi`` of the original Hamiltonian are measured with the
joint-state construction, pooling and solve shared with FixedGCIM, and the
lowest Ritz value of ``H f = E S f`` is reported with the reference energy.
This is the Hamiltonian pencil of Parrish and McMahon, arXiv:1909.08925v1,
Sec. II.C, Eqs. (5)-(8), with the time-evolved trial states of one fixed
step instead of exact evolution.
"""

